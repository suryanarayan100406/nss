def _strip_comments(text: str) -> str:
    """Drop whole-line comments, so a directive named in prose is not mistaken for
    one that is set. Every file here uses `#`."""
    return "\n".join(
        line for line in text.splitlines() if not line.strip().startswith("#")
    )


def _server_blocks(text: str) -> list[str]:
    """The `server { ... }` blocks of an Nginx file, braces balanced."""
    blocks, depth, start = [], 0, None
    for index, line in enumerate(text.splitlines()):
        if line.strip() == "server {":
            start = index
        if start is not None:
            depth += line.count("{") - line.count("}")
            if depth == 0:
                blocks.append("\n".join(text.splitlines()[start : index + 1]))
                start = None
    return blocks


def test_the_server_block_does_not_redefine_the_include_locations():
    """The include owns `location /` and `location ^~ /api/` in every mode.

    A second copy of either is a duplicate-location error, so `nginx -t` would fail
    at install time — on the one morning there is no room for it.

    Only the TLS server is checked: the port-80 block is a redirect and includes
    nothing, so its `location /` is both correct and necessary.
    """
    blocks = _server_blocks(NGINX_SITE.read_text(encoding="utf-8"))
    assert len(blocks) == 2, f"expected a redirect and a TLS server block, found {len(blocks)}"

    tls = [b for b in blocks if "listen      443 ssl;" in b]
    assert len(tls) == 1, "could not identify the TLS server block"
    code = _strip_comments(tls[0])

    assert "location / {" not in code, "the server block defines `location /`"
    assert "location ^~ /api/" not in code, "the server block defines the API location"
    assert "location ^~ /admin/" not in code, "the server block defines the portal location"
    assert "include /etc/nginx/nss-mode.inc;" in code


def test_the_server_block_forwards_the_client_address():
    """Without this the login lockout keys on 127.0.0.1 and one attacker locks out
    every admin, or none of them."""
    code = _strip_comments(NGINX_SITE.read_text(encoding="utf-8"))
    assert "proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;" in code


def test_the_server_block_sends_no_frame_denial():
    """The ceremony's reveal frames index.html inside its own page. A DENY here
    replaces the climax of the ceremony with a browser error page."""
    code = _strip_comments(NGINX_SITE.read_text(encoding="utf-8"))
    assert "X-Frame-Options" not in code


