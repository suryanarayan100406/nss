INSTALL_REWRITES = (
    ("/usr/local/sbin/nss-decommission", "{r}/usr/local/sbin/nss-decommission"),
    ("/etc/systemd/system/nss-inauguration.service", "{r}/etc/systemd/system/nss-inauguration.service"),
    ("/etc/sudoers.d/nss-inauguration", "{r}/etc/sudoers.d/nss-inauguration"),
    ("/etc/nginx/sites-available/nss", "{r}/etc/nginx/sites-available/nss"),
    ("/etc/nginx/sites-enabled/nss", "{r}/etc/nginx/sites-enabled/nss"),
    ("/etc/nginx/nss-mode.inc", "{r}/etc/nginx/nss-mode.inc"),
    ("/var/backups/nss-inauguration", "{r}/var/backups/nss-inauguration"),
    ("/var/log/nss-inauguration", "{r}/var/log/nss-inauguration"),
    ("/opt/nss-inauguration", "{r}/opt/nss-inauguration"),
    ("/usr/sbin/nginx", "{r}/stub/nginx"),
    ("/var/www/nss", "{r}/var/www/nss"),
)


class Sandbox:
    """A production layout in a temporary directory, with instrumented stubs."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.stub = root / "stub"
        self.probe = root / "probe.log"
        self.etc = root / "etc"
        self.web = root / "var" / "www" / "nss"
        self.opt = root / "opt" / "nss-inauguration"
        self.backups = root / "var" / "backups" / "nss-inauguration"
        self.src = root / "src"
        self.script = self.src / "deploy" / "install.sh"

        for path in (self.stub, self.probe.parent, self.web, self.src):
            path.mkdir(parents=True, exist_ok=True)

    # -- layout ------------------------------------------------------------

    @staticmethod
    def _write(path: Path, text: str) -> None:
        """Write the way Linux would: LF, never the host's CRLF."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")

    def build_site(self) -> None:
        for name in ("css", "js", "vendor", "assets", "admin"):
            (self.web / name).mkdir(parents=True, exist_ok=True)
        self._write(self.web / "index.html", "<html><title>NSS</title>permanent home</html>")
        self._write(self.web / "team.html", "<html>permanent team</html>")
        self._write(self.web / "nss_logo.jpg", "jpeg")
        self._write(self.web / "css" / "style.css", ":root{}")
        self._write(self.web / "js" / "main.js", "// main")
        self._write(self.web / "admin" / "old.html", "stale portal file")
        self._write(self.web / "inauguration.html", "<html>ceremony</html>")

    def build_source_tree(self) -> None:
        """A copy of the real deploy tree, so install.sh's SOURCE_DIR resolves here."""
        shutil.copytree(INAUGURATION / "backend", self.src / "backend")
        shutil.copytree(INAUGURATION / "web", self.src / "web")
        shutil.copytree(INAUGURATION / "deploy", self.src / "deploy")
        shutil.copy2(REPO / "inauguration.html", self.root / "inauguration.html")
        self._write(self.src / "README.md", "# runbook\n")

    def build_existing_config(self, site: str = "server { listen 80; }\n") -> None:
        """What a machine that already runs Nginx looks like.

        Note what is *not* created: nss-mode.inc. On a first install it genuinely
        does not exist, and on a re-install it is the backend's file to own — an
        installer that overwrote it would reset a live ceremony to coming_soon mode.
        """
        for directory in (
            self.etc / "nginx" / "sites-available",
            self.etc / "nginx" / "sites-enabled",
            self.etc / "systemd" / "system",
            self.etc / "sudoers.d",
        ):
            directory.mkdir(parents=True, exist_ok=True)
        self._write(self.etc / "nginx" / "sites-available" / "nss", site)

    def build_venv(self) -> None:
        """A venv whose python is a shim, so no package is ever downloaded.

        The shim also has to make the host behave like the VM. On Linux Python's
        stdout is UTF-8 with no newline translation; on Windows it is the ANSI code
        page and every ``\\n`` becomes ``\\r\\n``. The include contains an em dash and
        is compared byte for byte, so without this the test fails for a reason that
        cannot happen in production — the same trap the decommission sandbox hit.
        """
        python = self.opt / "venv" / "bin" / "python"
        self._write(
            python,
            "#!/bin/bash\n"
            "# Sandbox shim: pretend to install dependencies, and pass everything else\n"
            "# through to the real interpreter so the include really is rendered.\n"
            'if [ "$1" = "-m" ] && [ "$2" = "pip" ]; then exit 0; fi\n'
            'case "$2" in *"import fastapi"*) exit 0 ;; esac\n'
            f'PYTHONIOENCODING=utf-8 "{Path(sys.executable).as_posix()}" "$@" | tr -d "\\r"\n'
            "exit ${PIPESTATUS[0]}\n",
        )
        self._make_executable(python)

    # -- stubs -------------------------------------------------------------

    def _make_executable(self, path: Path) -> None:
        os.chmod(path, 0o755)
        if os.name == "nt":
            # MSYS decides `-x` partly on the extension; make the intent explicit.
            with open(path, "ab") as fh:
                fh.write(b"")

    def _stub(self, name: str, body: str) -> None:
        path = self.stub / name
        self._write(path, "#!/bin/bash\n" + body)
        self._make_executable(path)

    def build_stubs(self) -> None:
        probe = self.probe.as_posix()
        stub = self.stub.as_posix()

        self._stub("id", 'echo 0\n')
        # chown is the first thing that reaches outside the backup directory, so it
        # is instrumented: the probe line records how many snapshots already existed
        # when it ran, which is how the ordering claim below is made without relying
        # on filesystem timestamps.
        self._stub(
            "chown",
            f'echo "chown snapshots=$(ls -1 "{self.backups.as_posix()}" 2>/dev/null | wc -l)"'
            f' >> "{probe}"\nexit 0\n',
        )
        self._stub("useradd", f'echo "useradd $*" >> "{probe}"\nexit 0\n')
        self._stub("python3", "exit 0\n")
        self._stub("sudo", "exit 0\n")

        self._stub("systemctl", f'echo "systemctl $*" >> "{probe}"\nexit 0\n')

        # `install -o root` cannot work on the test host; keep everything else.
        self._stub(
            "install",
            "src=''; dst=''; mode=''\n"
            "while [ $# -gt 0 ]; do\n"
            "  case \"$1\" in\n"
            "    -o|-g) shift 2;;\n"
            "    -m) mode=\"$2\"; shift 2;;\n"
            "    -*) shift;;\n"
            "    *) if [ -z \"$src\" ]; then src=\"$1\"; else dst=\"$1\"; fi; shift;;\n"
            "  esac\n"
            "done\n"
            "[ -n \"$dst\" ] || exit 0\n"
            "if [ \"$src\" = /dev/null ]; then : > \"$dst\"; else cp \"$src\" \"$dst\"; fi\n"
            "[ -n \"$mode\" ] && chmod \"$mode\" \"$dst\"\n"
            "exit 0\n",
        )

        self._stub(
            "nginx",
            f'echo "nginx $*" >> "{probe}"\n'
            f'if [ "$1" = "-t" ] && [ -f "{stub}/fail-test" ]; then\n'
            '  echo "nginx: [emerg] invalid location modifier" >&2; exit 1\n'
            "fi\n"
            f'if [ "$1" = "-s" ] && [ -f "{stub}/fail-reload" ]; then\n'
            '  echo "nginx: [error] reload failed" >&2; exit 1\n'
            "fi\n"
            "exit 0\n",
        )

        self._stub(
            "visudo",
            f'if [ -f "{stub}/fail-visudo" ]; then\n'
            '  echo "syntax error" >&2; exit 1\n'
            "fi\n"
            "exit 0\n",
        )

        self._stub(
            "curl",
            "url=''\n"
            "while [ $# -gt 0 ]; do\n"
            "  case \"$1\" in\n"
            "    -H|--max-time|-o|-w) shift 2;;\n"
            "    -*) shift;;\n"
            "    *) url=\"$1\"; shift;;\n"
            "  esac\n"
            "done\n"
            f'echo "curl $url" >> "{probe}"\n'
            'printf \'{"ok":true,"site_mode":"coming_soon"}\'\n'
            "exit 0\n",
        )

    # -- the script under test --------------------------------------------

    def build_script(self) -> Path:
        text = INSTALL.read_text(encoding="utf-8")
        root = self.root.as_posix()
        for old, new in INSTALL_REWRITES:
            text = text.replace(old, new.format(r=root))
        self._write(self.script, text)
        self._make_executable(self.script)
        return self.script

    # -- running -----------------------------------------------------------

    def run(self, *args: str) -> subprocess.CompletedProcess:
        env = dict(os.environ)
        env["PATH"] = self.stub.as_posix() + os.pathsep + env.get("PATH", "")
        # stdin is closed rather than inherited: install.sh must never prompt, and a
        # child that waits on a terminal would hang here instead of failing.
        return subprocess.run(
            [BASH, self.script.as_posix(), *args],
            capture_output=True, text=True, env=env, timeout=180,
            stdin=subprocess.DEVNULL,
        )

    def probes(self) -> list[str]:
        if not self.probe.exists():
            return []
        return [line for line in self.probe.read_text(encoding="utf-8").splitlines() if line.strip()]

    def full(self) -> "Sandbox":
        self.build_site()
        self.build_source_tree()
        self.build_existing_config()
        self.build_venv()
        self.build_stubs()
        self.build_script()
        return self


