def test_the_sudoers_rule_forbids_arguments():
    """A command listed without an argument spec may be run with *any* arguments.
    The trailing "" is what makes the no-arguments guarantee enforced rather than
    merely intended."""
    text = SUDOERS.read_text(encoding="utf-8")
    rules = [
        line for line in text.splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]
    grants = [line for line in rules if "NOPASSWD" in line]
    assert len(grants) == 1, f"expected exactly one grant, found {len(grants)}"
    assert grants[0].strip().endswith('/usr/local/sbin/nss-decommission ""'), (
        "the rule does not restrict the argument vector"
    )
    assert "ALL=(root)" in grants[0]
    assert "ALL=NOPASSWD" not in grants[0].replace("ALL=(root) NOPASSWD", "")


