class RollbackSandbox(Sandbox):
    """The same layout, plus snapshots to roll back to."""

    def build_rollback(self) -> Path:
        self.rollback = self.root / "rollback.sh"
        text = ROLLBACK.read_text(encoding="utf-8")
        root = self.root.as_posix()
        for old, new in INSTALL_REWRITES:
            text = text.replace(old, new.format(r=root))
        self._write(self.rollback, text)
        self._make_executable(self.rollback)
        return self.rollback

    def snapshot(self, name: str, include: str, site: str, *, when: str) -> Path:
        """A deploy-style snapshot, dated explicitly.

        The mtime is set rather than inherited from creation order: rollback.sh picks
        the newest by `ls -1dt`, and filesystem timestamps have a resolution too coarse
        to rely on for two directories made a millisecond apart.
        """
        directory = self.backups / name
        self._write(directory / "nginx" / "nss-mode.inc", include)
        self._write(directory / "nginx" / "nss", site)
        self._write(directory / "site" / "index.html", f"<html>{name}</html>")

        subprocess.run(
            [BASH, "-c",
             "find . -type f ! -name MANIFEST.sha256 -print0 | sort -z "
             "| xargs -0 -r sha256sum > MANIFEST.sha256"],
            cwd=directory.as_posix(), check=True, capture_output=True,
        )
        subprocess.run(
            [BASH, "-c", f'touch -d "{when}" "{directory.as_posix()}"'],
            check=True, capture_output=True,
        )
        return directory

    def run_rollback(self, *args: str) -> subprocess.CompletedProcess:
        env = dict(os.environ)
        env["PATH"] = self.stub.as_posix() + os.pathsep + env.get("PATH", "")
        return subprocess.run(
            [BASH, self.rollback.as_posix(), *args],
            capture_output=True, text=True, env=env, timeout=120,
            stdin=subprocess.DEVNULL,
        )

    def full(self) -> "RollbackSandbox":
        super().full()
        self.build_rollback()
        return self


@pytest.fixture
def rollback_box(tmp_path: Path) -> RollbackSandbox:
    return RollbackSandbox(tmp_path).full()


def test_rollback_restores_the_newest_snapshot(rollback_box: RollbackSandbox):
    rollback_box.snapshot(
        "deploy-20260101T000000Z", "# old routing\n", "server { listen 80; }\n",
        when="2020-01-01 00:00:00",
    )
    newest = rollback_box.snapshot(
        "deploy-20260102T000000Z", "# good routing\n", "server { listen 443 ssl; }\n",
        when="2030-01-01 00:00:00",
    )

    # The site is broken: a bad transition left routing that does not work.
    include = rollback_box.etc / "nginx" / "nss-mode.inc"
    include.write_text("# broken\n", encoding="utf-8")
    site = rollback_box.etc / "nginx" / "sites-available" / "nss"
    site.write_text("server { broken }\n", encoding="utf-8")

    result = rollback_box.run_rollback()
    assert result.returncode == 0, f"rollback failed:\n{result.stdout}\n{result.stderr}"

    assert include.read_text(encoding="utf-8") == "# good routing\n"
    assert site.read_text(encoding="utf-8") == "server { listen 443 ssl; }\n"

    probes = rollback_box.probes()
    nginx_calls = [p.split()[1] for p in probes if p.startswith("nginx")]
    assert nginx_calls[:2] == ["-t", "-s"], (
        f"nginx was reloaded before the restored config was tested: {probes}"
    )
    assert "deploy-20260102T000000Z" in result.stdout
    # The state it replaced is kept, so a wrong rollback is itself reversible.
    assert "pre-rollback-" in result.stdout


def test_rollback_refuses_a_snapshot_that_fails_its_checksums(rollback_box: RollbackSandbox):
    """Restoring from a damaged snapshot could put a half-written file live, which is
    worse than the state it was meant to fix."""
    directory = rollback_box.snapshot(
        "deploy-20260101T000000Z", "# good routing\n", "server { listen 80; }\n",
        when="2020-01-01 00:00:00",
    )
    include = rollback_box.etc / "nginx" / "nss-mode.inc"
    include.write_text("# current\n", encoding="utf-8")

    # Something corrupted the snapshot after it was taken.
    (directory / "nginx" / "nss-mode.inc").write_text("# tampered\n", encoding="utf-8")

    result = rollback_box.run_rollback("--backup", "deploy-20260101T000000Z")
    assert result.returncode != 0
    assert "does not match its own checksums" in result.stderr + result.stdout
    assert include.read_text(encoding="utf-8") == "# current\n", "a bad snapshot was restored"
    assert not any(p.startswith("nginx -s reload") for p in rollback_box.probes())


