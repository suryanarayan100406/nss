"""The deploy scripts, and the two ways they are allowed to fail.

``install.sh`` and ``rollback.sh`` are the only things standing between a bad
configuration and a site that does not come back. Both are held to the same rule the
application follows: nothing is replaced until a copy of what it is replacing exists
and verifies, and no configuration file is swapped in until ``nginx -t`` has accepted
it — because Nginx reads its configuration on reload, not on write.

Each script is run for real, against a whole production layout in a temporary
directory with ``nginx``, ``systemctl``, ``curl``, ``id``, ``chown``, ``useradd``,
``visudo`` and ``install`` stubbed and instrumented. The stubs record what they were
asked to do, which is how the ordering assertions are made: that the snapshot is
written before the first thing is replaced, and that the reload never happens when
the test failed.

That is the same approach ``test_decommission.py`` uses, for the same reason — the
scripts keep literal absolute paths because a path that can be steered is a path that
can be aimed at the wrong file, so the sandbox rewrites them instead.
"""

